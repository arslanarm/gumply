/** The types offered by the picker and the slash menu, in Obsidian's order. */
export const CALLOUT_TYPES = [
  "note",
  "tip",
  "info",
  "success",
  "question",
  "warning",
  "danger",
  "bug",
  "example",
  "quote",
] as const;

export function calloutStyle(type: string): CalloutStyle {
  return ALIASES[type.toLowerCase()] ?? "note";
}

/** What an untitled callout shows (Obsidian: the capitalised type). */
export function defaultCalloutTitle(type: string): string {
  if (!type) return "Note";
  return type.charAt(0).toUpperCase() + type.slice(1).toLowerCase();
}

